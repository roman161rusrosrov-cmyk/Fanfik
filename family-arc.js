  function palette(chapter, photoIndex) {
    const sets = [
      ["#111827", "#334155", "#f59e0b"], ["#172554", "#1e3a8a", "#93c5fd"],
      ["#1f2937", "#374151", "#fca5a5"], ["#052e16", "#14532d", "#86efac"],
      ["#3f1d2e", "#7f1d1d", "#fecaca"], ["#0c4a6e", "#155e75", "#bae6fd"]
    ];
    return sets[(chapter + photoIndex) % sets.length];
  }

