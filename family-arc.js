  function renderPhotos(chapter, labels) {
    return `<div class="family-photo-grid" aria-label="Два сюжетных кадра главы ${chapter}">
      ${labels.map((label, i) => `<figure class="family-photo"><div class="family-photo-art">${sceneSVG(chapter, i + 1, label)}</div><figcaption><strong>${esc(label)}</strong><span>Глава ${chapter} · кадр ${i + 1} из 2 · без лиц</span></figcaption></figure>`).join("")}
    </div>`;
  }

  function renderArc(chapter) {
    const raw = EVENTS[chapter - 1];
    if (!raw) return "";
    const event = raw.split("|");
    const paragraphs = extraParagraphs(chapter, event);
    return `<section class="family-arc" data-family-arc="${chapter}">
      <div class="family-arc-head"><span>Расширенная сцена</span><h3>${ARC_NAMES[Math.ceil(chapter / 6) - 1]}</h3></div>
      ${paragraphs.map(p => `<p>${esc(p)}</p>`).join("")}
      ${renderPhotos(chapter, [event[1], event[2]])}
    </section>`;
  }

